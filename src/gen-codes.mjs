// Writes src/codes.mjs from the specification's tables (docs/spec.md): every mistake and warning
// code of §16.4 with when it is given and its explanation, every fault code of §13.4, and the standard library's
// signatures and what each gives (§14), for `stride doc`. `stride explain` reads
// codes.mjs, so its words are the spec's own; `stride selftest` says when they are not. Run it whenever the spec's
// codes change:
//
//   node src/gen-codes.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
export const SPEC_PATH = `${here}../docs/spec.md`;

// The codes of the spec's tables, from its text.
export function codesOf(spec) {
  const codes = {};
  for (const line of spec.split("\n")) {
    const m = line.match(/^\| ([SW]\d{3}) \| (.*?) \| (.*?) \|\s*$/);
    if (m) codes[m[1]] = { when: m[2].trim(), explanation: m[3].trim() };
    const f = line.match(/^\| (F\d{3}) \| (.*?) \|\s*$/);
    if (f) codes[f[1]] = { when: f[2].trim(), explanation: "" };
  }
  return codes;
}

// The standard library's entries of §14's tables: each with the section it stands in, its signatures and what it
// gives.
export function libraryOf(spec) {
  const out = [];
  let section = null;
  for (const line of spec.split("\n")) {
    const h = line.match(/^### (14\.\d) (.*)$/);
    if (h) section = `${h[1]} ${h[2]}`;
    else if (/^## /.test(line)) section = null;
    if (!section) continue;
    const m = line.match(/^\| (`[^|]*`) \| (.*?) \|\s*$/);
    if (!m || m[1] === "`l + m` (an operator, not a function)") continue;
    const signatures = [...m[1].matchAll(/`([^`]*)`/g)].map((x) => x[1]);
    out.push({ section, signatures, names: signatures.map((x) => x.match(/^(\w+)\(/)?.[1]).filter(Boolean), gives: m[2].trim() });
  }
  return out;
}

// Bundling gives every module the executable's URL; importing this module must not run its generator.
/* global STRIDE_BUNDLED */
const bundled = typeof STRIDE_BUNDLED !== "undefined" && STRIDE_BUNDLED;
if (!bundled && process.argv[1] === fileURLToPath(new URL(import.meta.url))) {
  const spec = readFileSync(SPEC_PATH, "utf8");
  const codes = codesOf(spec);
  const out = `// Generated by src/gen-codes.mjs from docs/spec.md (§13.4, §14, §16.4). Do not edit: change the spec
// and run the generator.
export const CODES = ${JSON.stringify(codes, null, 2)};

export const LIBRARY = ${JSON.stringify(libraryOf(spec), null, 2)};
`;
  writeFileSync(`${here}codes.mjs`, out);
  console.log(`${Object.keys(codes).length} codes written to src/codes.mjs`);
}
